        public static int MaximumLevel =>
            ExperienceByLevel.Length;


        public static int ExperienceForLevel(
            int level)
        {
            ValidateLevel(level);

            return ExperienceByLevel[
                level - 1
            ];
        }


        public static int AttributePointsForLevel(
            int level)
        {
            ValidateLevel(level);

            return AttributePointsByLevel[
                level - 1
            ];
        }


        public static bool IsValidLevel(
            int level)
        {
            return
                level >= 1 &&
                level <= MaximumLevel;
        }


        private static void ValidateLevel(
            int level)
        {
            if (!IsValidLevel(level))
            {
                throw new ArgumentOutOfRangeException(
                    nameof(level),
                    $"Level must be between 1 and {MaximumLevel}."
                );
            }
        }
